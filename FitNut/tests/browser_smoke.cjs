// Optional UI verification: run with Node.js and Playwright (Chromium) installed.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');

(async () => {
  const baseURL = process.env.FITNUT_URL || 'http://127.0.0.1:5000';
  if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(baseURL)) throw new Error('Use a local demo server.');
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ baseURL, timezoneId: 'America/New_York', viewport: { width: 1100, height: 900 } });
  const page = await context.newPage();
  page.setDefaultTimeout(60000);
  page.setDefaultNavigationTimeout(90000);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const email = `browser-${Date.now()}@example.test`;
  const password = 'Local-demo-only-42';
  const output = path.resolve('.test-results');
  await fs.mkdir(output, { recursive: true });
  try {
    const registered = await context.request.post('/register', { data: { first_name: 'Demo', last_name: 'User', email,
      password, password_confirmation: password } });
    assert.equal(registered.status(), 201);
    await page.goto('/login');
    await page.getByLabel('Email').fill(email);
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await page.waitForURL('**/dashboard');
    await page.getByRole('link', { name: 'Profile', exact: true }).click();
    assert.equal(await page.locator('select[name="allergy_status"]').inputValue(), 'not_provided');
    assert.equal(await page.getByRole('checkbox', { name: 'Milk', exact: true }).isDisabled(), true);
    await page.getByLabel('Age', { exact: true }).fill('25');
    await page.getByLabel('Height (cm)', { exact: true }).fill('175.25');
    await page.getByLabel('Weight (kg)', { exact: true }).fill('70');
    await page.getByLabel('Daily calorie target', { exact: true }).fill('2000');
    await page.getByLabel('Weekly activity target (minutes)', { exact: true }).fill('150');
    await page.locator('select[name="fitness_goal"]').selectOption('improve_fitness');
    await page.locator('select[name="fitness_level"]').selectOption('beginner');
    await page.locator('select[name="dietary_pattern"]').selectOption('vegetarian');
    await page.locator('select[name="allergy_status"]').selectOption('listed');
    await page.getByRole('button', { name: 'Save profile', exact: true }).click();
    await page.getByText('Select an allergy or enter one under other allergies', { exact: true }).waitFor();
    await page.getByRole('checkbox', { name: 'Milk', exact: true }).check();
    await page.getByRole('checkbox', { name: 'Peanut', exact: true }).check();
    await page.getByLabel('Other allergies', { exact: true }).fill('Kiwi');
    await page.getByLabel('Intolerances', { exact: true }).fill('Lactose');
    await page.getByLabel('Food preferences', { exact: true }).fill('No spicy food\nLess salt');
    await page.route('**/profile-data', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Simulated profile save failure' }) }));
    await page.getByRole('button', { name: 'Save profile', exact: true }).click();
    await page.getByText('Simulated profile save failure', { exact: true }).waitFor();
    assert.equal(await page.getByRole('checkbox', { name: 'Peanut', exact: true }).isChecked(), true);
    assert.equal(await page.getByLabel('Other allergies', { exact: true }).inputValue(), 'Kiwi');
    await page.unroute('**/profile-data');
    await page.getByRole('button', { name: 'Save profile', exact: true }).click();
    await page.getByText('Profile saved', { exact: true }).waitFor();
    await page.reload();
    assert.equal(await page.getByRole('checkbox', { name: 'Milk', exact: true }).isChecked(), true);
    assert.equal(await page.getByRole('checkbox', { name: 'Peanut', exact: true }).isChecked(), true);
    assert.equal(await page.getByLabel('Weight (kg)', { exact: true }).inputValue(), '70.00');
    assert.equal(await page.getByLabel('Intolerances', { exact: true }).inputValue(), 'Lactose');
    await page.screenshot({ path: path.join(output, 'profile.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'profile-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 1100, height: 900 });
    await page.locator('select[name="allergy_status"]').selectOption('none_reported');
    await page.getByRole('button', { name: 'Save profile', exact: true }).click();
    await page.getByText('Profile saved', { exact: true }).waitFor();
    await page.reload();
    assert.equal(await page.locator('select[name="allergy_status"]').inputValue(), 'none_reported');
    const profileResponse = await context.request.get('/profile-data');
    const savedProfile = (await profileResponse.json()).profile;
    assert.deepEqual(savedProfile.allergens, []);
    assert.deepEqual(savedProfile.other_allergies, []);
    assert.deepEqual(savedProfile.intolerances, ['Lactose']);
    assert.deepEqual(savedProfile.preferences, ['Less salt', 'No spicy food']);
    await page.getByRole('link', { name: 'Food', exact: true }).first().click();
    await page.getByLabel('Search the food database').fill('Bananas raw');
    await page.getByRole('button', { name: 'Search USDA foods' }).click();
    await page.locator('#food-results button').first().waitFor({ timeout: 20000 });
    const rawBanana = page.locator('#food-results button').filter({ hasText: /^Bananas, raw/ });
    await (await rawBanana.count() ? rawBanana.first() : page.locator('#food-results button').first()).click();
    await page.getByLabel('Quantity', { exact: true }).fill('0');
    await page.getByRole('button', { name: 'Add food to meal' }).click();
    assert.equal(await page.locator('#meal-draft').isVisible(), false);
    await page.getByLabel('Quantity', { exact: true }).fill('150');
    await page.getByRole('button', { name: 'Add food to meal' }).click();
    await page.locator('#draft-items li').first().waitFor();
    assert.match(await page.locator('#draft-items').innerText(), /Calories/);
    await page.getByLabel('Food name', { exact: true }).fill('Manual oats');
    await page.getByLabel('Quantity', { exact: true }).fill('1');
    await page.getByLabel('Unit', { exact: true }).fill('cup');
    await page.getByLabel('Calories', { exact: true }).fill('150');
    await page.getByRole('button', { name: 'Add food to meal' }).click();
    await page.waitForFunction(() => document.querySelectorAll('#draft-items li').length === 2);
    assert.equal(await page.locator('.record').count(), 0);
    await page.route('**/meals', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Simulated save failure. Please retry.' }) }));
    await page.getByRole('button', { name: 'Save meal', exact: true }).click();
    await page.getByText('Simulated save failure. Please retry.', { exact: true }).waitFor();
    assert.equal(await page.locator('#draft-items li').count(), 2);
    await page.unroute('**/meals');
    await page.getByRole('button', { name: 'Save meal', exact: true }).click();
    await page.getByText('Meal logged successfully', { exact: true }).waitFor();
    assert.equal(await page.locator('.record').count(), 2);
    await page.reload();
    assert.equal(await page.locator('.record').count(), 2);
    await page.getByLabel('Daily calorie target').fill('2000');
    await page.getByRole('button', { name: 'Save target' }).click();
    await page.getByText('Goal saved', { exact: true }).waitFor();
    await page.waitForFunction(() => document.getElementById('log-totals').textContent.includes('Target 2,000'));
    await page.screenshot({ path: path.join(output, 'food.png'), fullPage: true });

    const existingMealId = await page.locator('select[name="eating_event_id"] option').nth(1).getAttribute('value');
    await page.locator('select[name="eating_event_id"]').selectOption(existingMealId);
    await page.getByLabel('Food name', { exact: true }).fill('Water');
    await page.getByLabel('Quantity', { exact: true }).fill('1');
    await page.getByLabel('Unit', { exact: true }).fill('cup');
    await page.getByLabel('Calories', { exact: true }).fill('0');
    await page.getByRole('button', { name: 'Add food to meal' }).click();
    await page.locator('#draft-items li').first().waitFor();
    await page.getByRole('button', { name: 'Save meal', exact: true }).click();
    await page.getByText('Meal logged successfully', { exact: true }).waitFor();
    assert.equal(await page.locator('.record').count(), 3);

    await page.locator('.record').filter({ hasText: 'Manual oats' }).getByRole('button', { name: 'Edit', exact: true }).click();
    await page.getByLabel('Food name', { exact: true }).fill('Updated oats');
    await page.getByRole('button', { name: 'Review changes' }).click();
    await page.getByRole('button', { name: 'Confirm and save' }).click();
    await page.getByText('Record updated', { exact: true }).waitFor();
    assert.match(await page.locator('.record-list').innerText(), /Updated oats/);
    await page.getByRole('link', { name: 'Activity', exact: true }).click();
    await page.getByLabel('Activity', { exact: true }).fill('Walking');
    await page.locator('select[name="intensity"]').selectOption('moderate');
    await page.getByLabel('Body weight (kg)', { exact: true }).fill('70');
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('0');
    await page.getByRole('button', { name: 'Review activity' }).click();
    assert.equal(await page.locator('#entry-review').isVisible(), false);
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('30');
    await page.getByRole('button', { name: 'Review activity' }).click();
    await page.locator('#entry-review').waitFor({ state: 'visible' });
    assert.match(await page.locator('#review-details').innerText(), /139.65.*estimate/);
    assert.equal(await page.locator('.record').count(), 0);
    await page.getByRole('button', { name: 'Confirm and save' }).click();
    await page.getByText('Record saved', { exact: true }).waitFor();
    await page.reload();
    assert.equal(await page.locator('.record').count(), 1);
    assert.match(await page.locator('.record').innerText(), /139.65.*estimate/);
    await page.waitForFunction(() => !document.getElementById('log-totals').textContent.includes('Loading'));
    await page.screenshot({ path: path.join(output, 'activity.png'), fullPage: true });
    await page.getByRole('button', { name: 'Edit', exact: true }).click();
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('45');
    await page.getByRole('button', { name: 'Review changes' }).click();
    await page.getByRole('button', { name: 'Confirm and save' }).click();
    await page.getByText('Record updated', { exact: true }).waitFor();
    assert.match(await page.locator('.record').innerText(), /45(?:\.0)? min/);
    await page.getByLabel('Activity', { exact: true }).fill('Walking');
    await page.locator('select[name="intensity"]').selectOption('moderate');
    await page.getByLabel('Duration (minutes)', { exact: true }).fill('30');
    await page.getByRole('button', { name: 'Review activity' }).click();
    await page.getByRole('button', { name: 'Confirm and save' }).click();
    await page.getByRole('button', { name: 'Keep overlapping activity and save' }).waitFor();
    await page.getByRole('button', { name: 'Back to form' }).click();
    assert.equal(await page.locator('.record').count(), 1);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'activity-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Browser smoke passed: profile create/edit/allergies/failure/retry, USDA lookup, meal save/edit, goals, activity review/estimates/edit, reload persistence, desktop/mobile, no page errors.');
    console.log('Demo account:', email, '(password is the fixed local test password in this script).');
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'browser-failure.png'), fullPage: true });
    console.error('Page URL:', page.url(), 'Page errors:', errors);
    console.error((await page.locator('body').innerText()).slice(0, 3500));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
